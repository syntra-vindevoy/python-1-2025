def is_real_anagram(word: str) -> bool:
    with open("words.txt") as f:
        words = f.read().split("\n")

        found = False
        anagram = False

        for w in words:
            if w == word:
                found = True
            elif is_anagram(w, word):
                anagram = True

            if anagram and found:
                return True

        return False

